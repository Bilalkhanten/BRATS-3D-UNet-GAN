def fmt(v):
    return f"`{v}`".replace("|", "\\|")


def main():
    lines = ["# Configuration reference", "",
             "*Generated by `scripts/gen_config_docs.py` from `bratsgan/config.py`; do not edit by hand.*", "",
             "Every experiment is a JSON file in `configs/` that overrides a subset of these defaults. Individual keys can be overridden "
             "on the command line with `--set key=value` (values are parsed as JSON), for example:", "",
             "```bash", "python -m bratsgan.train --config configs/a5_full.json --set name=demo epochs_seg=10 patch=[64,64,64]", "```", ""]
    seen = set()
    for title, keys in GROUPS:
        lines += [f"## {title}", "", "| Key | Default | Meaning |", "| --- | --- | --- |"]
        for k in keys:
            seen.add(k)
            lines.append(f"| `{k}` | {fmt(DEFAULTS[k])} | {DOC.get(k, '')} |")
        lines.append("")
    missing = [k for k in DEFAULTS if k not in seen]
    assert not missing, f"undocumented keys: {missing}"
    out = Path(__file__).resolve().parents[1] / "docs" / "configuration.md"
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
